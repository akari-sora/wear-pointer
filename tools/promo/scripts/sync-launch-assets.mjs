#!/usr/bin/env node
// Copies watch screenshots / recordings for the Launch video into public/launch/
// and writes src/launch/available.generated.ts so assets.ts can pick the first
// candidate that exists (fresh capture > placeholder).
//
//   node scripts/sync-launch-assets.mjs
//
// Sources (later wins on name clash):
//   ../store-assets/screens/*.{png,jpg,webp,mp4,webm,mov}
//   ../../docs/assets/icon-1024.png  -> icon.png
import { copyFileSync, existsSync, mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, extname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const promo = resolve(here, "..");
const out = join(promo, "public", "launch");
const screens = resolve(promo, "..", "store-assets", "screens");
const icon = resolve(promo, "..", "..", "docs", "assets", "icon-1024.png");
const exts = new Set([".png", ".jpg", ".jpeg", ".webp", ".mp4", ".webm", ".mov"]);

rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });

const copied = [];
if (existsSync(screens)) {
  for (const name of readdirSync(screens).sort()) {
    if (!exts.has(extname(name).toLowerCase())) continue;
    copyFileSync(join(screens, name), join(out, name));
    copied.push(name);
  }
} else {
  console.warn(`warning: ${screens} not found`);
}
if (existsSync(icon)) {
  copyFileSync(icon, join(out, "icon.png"));
  copied.push("icon.png");
}

const ts = `// Generated by scripts/sync-launch-assets.mjs. Do not edit by hand.
export const AVAILABLE: readonly string[] = ${JSON.stringify(copied, null, 2)};
`;
writeFileSync(join(promo, "src", "launch", "available.generated.ts"), ts);
console.log(`public/launch: ${copied.join(", ")}`);
